#!/usr/bin/env python3
"""Generate ConPanqueque/Code/Table.lean from the CodeScan dump."""
import sys, re, collections
txt = open(sys.argv[1]).read().split("\n@@\n")
entries = collections.OrderedDict()
def add(n, b):
    n = " ".join(n.split()); b = " ".join(b.split())
    assert b.startswith("Option.some "), b[:80]
    b = b[len("Option.some "):]
    entries.setdefault(n, b)
for l in txt:
    if l.startswith("UNHANDLED") or "|||" not in l: continue
    binders = []
    body = l
    while body.startswith("FAM"):
        m = re.match(r"FAM((?:\[[^\]]*\])*) (.*)", body, re.S)
        binders += re.findall(r"\[([^\]]*)\]", m.group(1)); body = m.group(2)
    n, b = body.split("|||", 1)
    vals = [{}]
    for bd in binders:
        v, ty = [x.strip() for x in bd.split(":", 1)]
        if ty == "ℕ":
            lim = None
            for bd2 in binders:
                mm = re.search(r": %s < (\d+)" % v, bd2)
                if mm: lim = int(mm.group(1))
            vals = [dict(d, **{v: str(i)}) for d in vals for i in range(lim)]
        elif ty == "Big.BitOp":
            vals = [dict(d, **{v: "ConPanqueque.T.Big.BitOp." + c}) for d in vals for c in ["and", "or", "xor"]]
        elif ty == "Bool":
            vals = [dict(d, **{v: c}) for d in vals for c in ["true", "false"]]
    for d in vals:
        nn, bb = n, b
        for v, x in d.items():
            nn = re.sub(r"\b%s\b" % re.escape(v), "(%s)" % x, nn)
            bb = re.sub(r"(?<![.\w])%s\b" % re.escape(v), "(%s)" % x, bb)
        add(nn, bb)
out = ["import ConPanqueque.Front.Top", "", "/-! # The concrete code table (generated by scripts/gen_code_table.py) -/", "",
       "open Flapjack Flapjack.Pancake.PanLang", "", "namespace ConPanqueque.Code", "",
       "noncomputable def codeEntries (C : ConPanqueque.T.Ctx) : List (MlS × (List (MlS × ShapeHOL) × ProgHOL 64 × ShapeHOL)) := ["]
items = ["  (%s, %s)" % (n, b) for n, b in entries.items()]
items.append("  (ConPanqueque.Front.fFeed, (ConPanqueque.Front.feedPs.map (fun p => (p, ShapeHOL.one)), ConPanqueque.T.prologue ConPanqueque.Front.feedL ConPanqueque.Front.feedCore, ShapeHOL.one))")
out.append(",\n".join(items)); out += ["]", "", "end ConPanqueque.Code", ""]
open("ConPanqueque/Code/Table.lean", "w").write("\n".join(out))
print(len(items), "entries")
