#!/usr/bin/env python3
"""Generate ConPanqueque/Prelude/Text.lean from con-leche's committed prelude.

The module proves `builtinPreludeText = String.ofList (C00 ++ … ++ C61)` (a kernel-only
definitional check, added with `addDecl` because the elaborator's defeq check of a 15.7 KB literal
does not finish) and the UTF-8 size of the text.  Run from the repository root:
    python3 scripts/gen_prelude_text.py          # writes the module
    python3 scripts/gen_prelude_text.py --check  # exits 1 if the module is stale
"""
import sys

SRC = 'deps/con-leche/pins/leanprover-lean4-v4.36.0.prelude.ndjson'
OUT = 'ConPanqueque/Prelude/Text.lean'

src = open(SRC, encoding='utf-8').read()
chunks, cur, bl = [], [], 0
for c in src:
    cur.append(c)
    bl += len(c.encode())
    if bl >= 256 and bl % 8 == 0:
        chunks.append(cur)
        cur, bl = [], 0
if cur:
    chunks.append(cur)


def ch(c):
    return "'\\x%02x'" % ord(c) if ord(c) < 128 else "'\\u%04x'" % ord(c)


names = ['C%02d' % i for i in range(len(chunks))]
out = ['''import Lean
import ConLeche.Frontend.Prelude

/-! # The built-in prelude's text, in checkable pieces

**Generated by `scripts/gen_prelude_text.py` from
`deps/con-leche/pins/leanprover-lean4-v4.36.0.prelude.ndjson` — do not edit.**

`preludeText_eq`: con-leche's `builtinPreludeText` (an `include_str` of that file) is
`String.ofList` of the concatenated character chunks `C00 … C%02d`.  The equation is definitional;
it is added with `addDecl`, so only the kernel checks it (the elaborator's defeq check of the
literal does not finish).  `preludeText_size`: its UTF-8 encoding has %d bytes. -/

namespace ConPanqueque.Prelude.Text
''' % (len(chunks) - 1, len(src.encode()))]
for n, c in zip(names, chunks):
    out.append('def %s : List Char := [%s]\n' % (n, ', '.join(ch(x) for x in c)))
out.append('''open Lean Elab Command

set_option maxRecDepth 1000000 in
run_cmd liftCoreM do
  let lc := mkConst ``Char
  let names : List Name := [%s]
  let l := names.foldr (fun n acc => mkApp3 (mkConst ``List.append [0]) lc (mkConst n) acc)
    (mkApp (mkConst ``List.nil [0]) lc)
  let ty := mkApp3 (mkConst ``Eq [1]) (mkConst ``String) (mkConst ``ConLeche.Frontend.builtinPreludeText)
    (mkApp (mkConst ``String.ofList) l)
  let v := mkApp2 (mkConst ``Eq.refl [1]) (mkConst ``String) (mkConst ``ConLeche.Frontend.builtinPreludeText)
  addDecl (.thmDecl { name := `ConPanqueque.Prelude.Text.preludeText_eq, levelParams := [], type := ty, value := v })
''' % ', '.join('`ConPanqueque.Prelude.Text.' + n for n in names))
for n, c in zip(names, chunks):
    out.append('theorem %s_size : %s.utf8Encode.size = %d := by decide +kernel\n' % (n, n, len(''.join(c).encode())))
out.append('''theorem preludeText_size : ConLeche.Frontend.builtinPreludeText.toUTF8.size = %d := by
  rw [preludeText_eq, String.toUTF8_eq_toByteArray, String.toByteArray_ofList]
  simp only [List.append_eq, List.append_nil, List.utf8Encode_append, ByteArray.size_append, %s]

end ConPanqueque.Prelude.Text
''' % (len(src.encode()), ', '.join(n + '_size' for n in names)))
text = '\n'.join(out)
if '--check' in sys.argv:
    sys.exit(0 if open(OUT, encoding='utf-8').read() == text else 1)
open(OUT, 'w', encoding='utf-8').write(text)
